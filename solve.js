// trim spaces and tabs at both ends
function trimLine(line) {
  let a = 0, b = line.length;
  while (a < b && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  return line.slice(a, b);
}

function isBlank(line) {
  return isBlankLine(line);
}

// FENCE_OPEN: /^```([A-Za-z0-9_+-]*)[ \t]*$/ -> lang or null
function fenceOpen(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return null;
  let i = 3;
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if ((c >= 65 && c <= 90) || (c >= 97 && c <= 122) || (c >= 48 && c <= 57) || c === 95 || c === 43 || c === 45) i++;
    else break;
  }
  const lang = line.slice(3, i);
  while (i < line.length) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return null;
    i++;
  }
  return lang;
}

function isFenceClose(line) {
  if (line.charCodeAt(0) !== 96 || line.charCodeAt(1) !== 96 || line.charCodeAt(2) !== 96) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

// heading: /^(#{1,6})[ \t]+(.*?)[ \t]*$/ with non-empty text -> {depth, text} or null
function headingOf(line) {
  let n = 0;
  while (n < line.length && line.charCodeAt(n) === 35) n++;
  if (n === 0 || n > 6) return null;
  if (n >= line.length) return null;
  const c = line.charCodeAt(n);
  if (c !== 32 && c !== 9) return null;
  let a = n;
  while (a < line.length && (line.charCodeAt(a) === 32 || line.charCodeAt(a) === 9)) a++;
  let b = line.length;
  while (b > a && (line.charCodeAt(b - 1) === 32 || line.charCodeAt(b - 1) === 9)) b--;
  if (b === a) return null;
  return { depth: n, text: line.slice(a, b) };
}

function isHr(line) {
  if (line.length < 3) return false;
  const a = line.charCodeAt(0), b = line.charCodeAt(1), d = line.charCodeAt(2);
  if (!((a === 45 && b === 45 && d === 45) || (a === 42 && b === 42 && d === 42))) return false;
  for (let i = 3; i < line.length; i++) {
    const c = line.charCodeAt(i);
    if (c !== 32 && c !== 9) return false;
  }
  return true;
}

function endsParagraph(line) {
  return isBlank(line) || fenceOpen(line) !== null || headingOf(line) !== null || isHr(line);
}

const ESCAPABLE = new Set(['\\', '`', '*', '_', '[', ']', '(', ')', '#', '+', '-', '.', '!', '>']);
const ESCAPES = { '>': '&gt;' };

function findUnescaped(s, what, from) {
  for (let j = from; j <= s.length - what.length; j++) {
    if (s[j] === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (s.startsWith(what, j)) return j;
  }
  return -1;
}

function findSingleStar(s, from) {
  for (let j = from; j < s.length; j++) {
    const c = s[j];
    if (c === '\\' && j + 1 < s.length && ESCAPABLE.has(s[j + 1])) {
      j++;
      continue;
    }
    if (c !== '*') continue;
    if (s[j + 1] === '*') {
      j++;
      continue;
    }
    return j;
  }
  return -1;
}

const WS_RE = /\s/;
const SPECIAL_RE = /[\\`*\[&<>"']/g;

/** Inline markdown rendered into `out` (an array of strings). */
function inline(s, env, out) {
  const n = s.length;
  SPECIAL_RE.lastIndex = 0;
  let run = 0;
  let m;
  while ((m = SPECIAL_RE.exec(s)) !== null) {
    const i = m.index;
    const c = m[0];
    if (c === '\\') {
      if (i + 1 < n && ESCAPABLE.has(s[i + 1])) {
        if (i > run) out.push(s.slice(run, i));
        out.push(ESCAPES[s[i + 1]] || s[i + 1]);
        run = i + 2;
        SPECIAL_RE.lastIndex = i + 2;
      } else {
        SPECIAL_RE.lastIndex = i + 1;
      }
      continue;
    }
    if (c === '`') {
      const j = s.indexOf('`', i + 1);
      if (j > i + 1) {
        if (i > run) out.push(s.slice(run, i));
        out.push('<code>');
        pushEsc(out, s, i + 1, j);
        out.push('</code>');
        run = j + 1;
        SPECIAL_RE.lastIndex = j + 1;
      } else {
        SPECIAL_RE.lastIndex = i + 1;
      }
      continue;
    }
    if (c === '*') {
      if (s[i + 1] === '*') {
        const j = findUnescaped(s, '**', i + 2);
        if (j > i + 2) {
          if (i > run) out.push(s.slice(run, i));
          out.push('<strong>');
          inline(s.slice(i + 2, j), env, out);
          out.push('</strong>');
          run = j + 2;
          SPECIAL_RE.lastIndex = j + 2;
        } else {
          SPECIAL_RE.lastIndex = i + 2;
        }
        continue;
      }
      const j = findSingleStar(s, i + 1);
      if (j > i + 1) {
        if (i > run) out.push(s.slice(run, i));
        out.push('<em>');
        inline(s.slice(i + 1, j), env, out);
        out.push('</em>');
        run = j + 1;
        SPECIAL_RE.lastIndex = j + 1;
      } else {
        SPECIAL_RE.lastIndex = i + 1;
      }
      continue;
    }
    if (c === '[') {
      const k = findUnescaped(s, ']', i + 1);
      const mm = k !== -1 && s[k + 1] === '(' ? s.indexOf(')', k + 2) : -1;
      const target = mm === -1 ? '' : s.slice(k + 2, mm);
      if (target !== '' && !WS_RE.test(target)) {
        if (i > run) out.push(s.slice(run, i));
        const href = env.link(target);
        out.push('<a href="');
        pushEsc(out, href, 0, href.length);
        out.push('">');
        inline(s.slice(i + 1, k), env, out);
        out.push('</a>');
        run = mm + 1;
        SPECIAL_RE.lastIndex = mm + 1;
        continue;
      }
      SPECIAL_RE.lastIndex = i + 1;
      continue;
    }
    // & < > " '
    if (i > run) out.push(s.slice(run, i));
    out.push(c === '&' ? '&amp;' : c === '<' ? '&lt;' : c === '>' ? '&gt;' : c === '"' ? '&quot;' : '&#39;');
    run = i + 1;
    SPECIAL_RE.lastIndex = i + 1;
  }
  if (n > run) out.push(s.slice(run, n));
}

function inlineToString(s, env) {
  const out = [];
  inline(s, env, out);
  return out.join('');
}

/** Rendered markdown: { html, toc, excerpt }. `slugify` is the per-run cached slug function. */
function renderMarkdown(src, env, slugify) {
  const lines = src.split('\n');
  const ids = new Set();
  const out = [];
  const toc = [];
  let excerpt = null;
  let i = 0;
  const L = lines.length;
  while (i < L) {
    const line = lines[i];
    if (isBlank(line)) { i++; continue; }
    const lang = fenceOpen(line);
    if (lang !== null) {
      i++;
      out.push(`<pre><code${lang === '' ? '' : ` class="language-${lang}"`}>`);
      while (i < L && !isFenceClose(lines[i])) {
        pushEsc(out, lines[i], 0, lines[i].length);
        out.push('\n');
        i++;
      }
      i++;
      out.push('</code></pre>\n');
      continue;
    }
    const heading = headingOf(line);
    if (heading !== null) {
      const id = uniqueSlug(slugify(heading.text), ids);
      out.push(`<h${heading.depth} id="${id}">`);
      if (heading.depth === 2 || heading.depth === 3) {
        const html = inlineToString(heading.text, env);
        toc.push({ level: heading.depth, id, html });
        out.push(html);
      } else {
        inline(heading.text, env, out);
      }
      out.push(`</h${heading.depth}>\n`);
      i++;
      continue;
    }
    if (isHr(line)) {
      out.push('<hr>\n');
      i++;
      continue;
    }
    if (line.charCodeAt(0) === 62) { // '>'
      const body = [];
      while (i < L && lines[i].charCodeAt(0) === 62) {
        let l = lines[i++];
        l = l.startsWith('> ') ? l.slice(2) : l.slice(1);
        l = trimLine(l);
        if (l !== '') body.push(l);
      }
      if (body.length === 0) out.push('<blockquote>\n</blockquote>\n');
      else {
        out.push('<blockquote>\n<p>');
        inline(body.join('\n'), env, out);
        out.push('</p>\n</blockquote>\n');
      }
      continue;
    }
    const c0 = line.charCodeAt(0);
    const isBullet = (c0 === 45 || c0 === 42) && line.charCodeAt(1) === 32;
    let ordered = null;
    if (!isBullet && c0 >= 48 && c0 <= 57) {
      // /^(\d{1,9})\. (.*)$/
      let j = 0;
      while (j < line.length && j < 9 && line.charCodeAt(j) >= 48 && line.charCodeAt(j) <= 57) j++;
      if (j >= 1 && j < line.length && line.charCodeAt(j) === 46 && line.charCodeAt(j + 1) === 32) {
        ordered = { start: Number(line.slice(0, j)) };
      }
    }
    if (isBullet || ordered !== null) {
      const isOrdered = ordered !== null;
      const items = [];
      while (i < L) {
        const ln = lines[i];
        if (isOrdered) {
          let j = 0;
          while (j < ln.length && j < 9 && ln.charCodeAt(j) >= 48 && ln.charCodeAt(j) <= 57) j++;
          if (j >= 1 && j < ln.length && ln.charCodeAt(j) === 46 && ln.charCodeAt(j + 1) === 32) {
            items.push(trimLine(ln.slice(j + 2)));
            i++;
            continue;
          }
        } else {
          const cc = ln.charCodeAt(0);
          if ((cc === 45 || cc === 42) && ln.charCodeAt(1) === 32) {
            items.push(trimLine(ln.slice(2)));
            i++;
            continue;
          }
        }
        // CONTINUED: /^ {2,}\S/
        if (ln.length >= 3 && ln.charCodeAt(0) === 32 && ln.charCodeAt(1) === 32) {
          let k = 2;
          while (k < ln.length && ln.charCodeAt(k) === 32) k++;
          if (k < ln.length && !WS_RE.test(ln[k])) {
            items[items.length - 1] += `\n${trimLine(ln)}`;
            i++;
            continue;
          }
        }
        break;
      }
      const tag = isOrdered ? 'ol' : 'ul';
      out.push(isOrdered && ordered.start !== 1 ? `<ol start="${ordered.start}">\n` : `<${tag}>\n`);
      for (let k = 0; k < items.length; k++) {
        out.push('<li>');
        inline(items[k], env, out);
        out.push('</li>\n');
      }
      out.push(`</${tag}>\n`);
      continue;
    }
    // paragraph
    const body = [trimLine(line)];
    i++;
    while (i < L && !endsParagraph(lines[i])) body.push(trimLine(lines[i++]));
    const text = body.join('\n');
    out.push('<p>');
    if (excerpt === null) {
      const html = inlineToString(text, env);
      excerpt = html;
      out.push(html);
    } else {
      inline(text, env, out);
    }
    out.push('</p>\n');
  }
  return { html: out.join(''), toc, excerpt: excerpt ?? '' };
}

